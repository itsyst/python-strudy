#🧩 Övning 101 – Expressions
def print_prompt():
    print(f"4 - 2 = ",4 - 2)
    print(f"2 * 5.0 =", 2 * 5.0)
    print(f"(2 - 4) * 5.0 = ", (2 - 4) * 5.0)
    print(f"10 / 2 = ", 10 / 2)
    print(f"11 / 3 = ", 11 / 3)
    print(f"11 // 3 = ", 11 // 3)
    a = 2 * 3
    print(f"{a} - 2.0 = ", a - 2.0)

print_prompt()
